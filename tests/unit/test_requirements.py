"""tests/unit/test_requirements.py

requirements.txt is uv.lock, exported (Known problem 14 in
docs/architecture.md). The Docker image and `make install` install it with
pip, and a file of floors, resolved fresh on 2026-11-12, drifted from the
lock on 106 of 173 packages: pyarrow 26 among them, which refuses the
pinned NumPy, so every table on the dashboard failed. `make requirements`
writes the file from the lock; these tests keep the two equal.
"""

import os
import shutil
import subprocess
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[2]
REQUIREMENTS = (ROOT / "requirements.txt").read_text(encoding="utf-8")
MAKEFILE = (ROOT / "Makefile").read_text(encoding="utf-8")

# The one recipe. The Makefile's requirements target runs it with
# --output-file requirements.txt, and uv writes that command into the
# file's header. --no-editable makes the package's own line ".", which
# installs it; --extra dev keeps pytest and the other tools make test and
# make lint need, as CI's `uv sync --locked --extra dev` does.
EXPORT = (
    "uv export --format requirements.txt --frozen --no-hashes --no-editable --extra dev"
)
WRITE = f"{EXPORT} --output-file requirements.txt"


def _lines(text: str) -> list[str]:
    """The requirement lines: comments, uv's "# via" notes and blanks out."""
    found = []
    for line in text.splitlines():
        line = line.split(" #", 1)[0].strip()
        if line and not line.startswith("#"):
            found.append(line)
    return found


def _requirements(text: str) -> set[str]:
    """Each requirement parsed and written back one way (name, version,
    markers), whatever spacing or quoting uv used. "." is the package."""
    found = set()
    for line in _lines(text):
        if line == ".":
            found.add(line)
            continue
        req = Requirement(line)
        marker = f" ; {req.marker}" if req.marker else ""
        found.add(f"{canonicalize_name(req.name)}{req.specifier}{marker}")
    return found


def _uv() -> str:
    """The uv that runs this suite (uv run sets UV), or the one on PATH. CI
    and both workflows install uv, so there a missing one is a failure."""
    found = os.environ.get("UV") or shutil.which("uv")
    if found is None:
        if os.environ.get("CI"):
            pytest.fail("uv is not on PATH, and CI installs it")
        pytest.skip("uv is not installed")
    return found


def test_every_requirement_is_an_exact_version():
    """No floors: each line pins one version, so pip installs what the lock
    holds and nothing newer (pyarrow 26 came in through a floor)."""
    loose = [
        line
        for line in _lines(REQUIREMENTS)
        if line != "." and not str(Requirement(line).specifier).startswith("==")
    ]
    assert not loose, loose


def test_requirements_txt_is_uv_lock_exported():
    exported = subprocess.run(
        [_uv(), *EXPORT.split()[1:]],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
        timeout=120,
    ).stdout
    have, want = _requirements(REQUIREMENTS), _requirements(exported)
    assert have == want, (
        "requirements.txt differs from uv.lock; run make requirements. "
        f"Only in requirements.txt: {sorted(have - want)[:8]}. "
        f"Only in uv.lock: {sorted(want - have)[:8]}."
    )


def test_make_requirements_writes_it_with_the_same_command():
    body = MAKEFILE.split("\nrequirements:\n", 1)[1].split("\n\n", 1)[0]
    assert body.strip() == WRITE
    header = REQUIREMENTS.splitlines()[:2]
    assert header[0].startswith("# This file was autogenerated by uv"), header
    assert header[1].lstrip("#").strip() == WRITE, header


def test_the_pins_the_models_rely_on_come_through():
    """pyproject.toml pins these exactly (the boosters link against NumPy's
    ABI; a pandas downgrade crashed LightGBM); the export keeps them."""
    pins = _requirements(REQUIREMENTS)
    for pin in ("numpy==1.26.4", "pandas==2.2.2", "sqlalchemy==2.0.30"):
        assert pin in pins, pin
